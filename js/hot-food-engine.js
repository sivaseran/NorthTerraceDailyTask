async function chooseAssignee(date,time){
  const [users,av,tasks]=await Promise.all([getUsers(),getStaffAvailability(),getTasksForDate(date,{ensure:false})]);
  const people=users.filter(u=>u.active!==false&&(u.role==='staff'||u.role==='assignee'));
  const t=mins(time), week=av?.week||{};
  const available=people.filter(p=>parseShift(week?.[p.id]?.[dayLower(date)]||'').some(w=>t>=w.a&&t<w.b));
  const pool=available.length?available:people;
  const slot=slotForClock(time,date);
  const scored=pool.map(p=>({p,load:tasks.filter(x=>x.slotId===slot&&x.assignedTo===p.id&&x.status!=='cancelled').reduce((a,x)=>a+(Number(x.effortMinutes)||0),0)})).sort((a,b)=>a.load-b.load||String(a.p.id).localeCompare(String(b.p.id)));
  return scored[0]?.p||null;
}
async function upsertHFTask(id,data){
  const ref=doc(db,'dailyTasks',id), snap=await getDoc(ref);
  if(snap.exists()) return {id,...snap.data()};
  const assignee=data.assignedTo?null:await chooseAssignee(data.date,data.sourceTime||data.checkpoint||'06:00');
  const row={hotFood:true,reportCategory:'Hot Food',status:'pending',photoRequired:false,effortMinutes:5,assignedTo:assignee?.id||'',assignedName:assignee?.name||'Unassigned',...data,createdAt:serverTimestamp(),updatedAt:serverTimestamp()};
  return runTransaction(db,async tx=>{const snap=await tx.get(ref);if(snap.exists())return {id,...snap.data()};tx.set(ref,row);return {id,...row};});
}
async function cancelLegacyTemperatureTasks(date){
  // The controlled Hot Food module replaces the old fixed :30 temperature tasks.
  // Cancel only today's generated daily instances; weekly templates, assignees, effort and times remain untouched.
  const q=await getDocs(query(collection(db,'dailyTasks'),where('date','==',date)));
  for(const d of q.docs){
    const x=d.data();
    const legacy=!x.hotFood && /^Check hot food temperature\s+\d{1,2}:\d{2}$/i.test(String(x.taskName||'').trim());
    if(legacy&&activeStatus(x)) await updateDoc(d.ref,{status:'cancelled',cancelReason:'Replaced by controlled Hot Food compliance workflow',updatedAt:serverTimestamp()});
  }
}

const LEGACY_HF_NAME=/^Check hot food temperature\s+\d{1,2}:\d{2}$/i;
// One-time, history-preserving transition. Deactivate the old *future template
// rules*, rather than merely hiding their daily instances (which would
// otherwise be regenerated by schedule reconciliation).
export async function retireLegacyHotFoodTemplates(effectiveFrom){
  const cfg=await getHotFoodConfig();if(cfg.enabled!==true)return {retired:0};
  const marker=doc(db,'system','hotFoodLegacyTemplateRetirementV4'),state=await getDoc(marker);
  if(state.exists()&&state.data()?.done===true)return {retired:0,alreadyDone:true};
  const templates=(await getWeeklyTemplate()).filter(t=>LEGACY_HF_NAME.test(String(t.taskName||'').trim()));
  let retired=0;
  for(const t of templates){
    const schedule=structuredClone(t.schedule||{});
    let changed=false;
    for(const day of ['Mon','Tue','Wed','Thu','Fri','Sat','Sun']){
      const entry=schedule[day];if(!entry)continue;
      const versions=Array.isArray(entry.versions)?entry.versions:[];
      if(versions.some(v=>v.effectiveFrom===effectiveFrom&&v.active===false))continue;
      if(!versions.some(v=>v.active!==false))continue;
      for(const v of versions){if(v.active!==false&&!v.effectiveTo&&String(v.effectiveFrom||'')<effectiveFrom)v.effectiveTo=previousDate(effectiveFrom);}
      versions.push({effectiveFrom,active:false,slotId:'',assigneeId:'',assigneeKey:'',legacyAssignee:'',effortMinutes:null,sourceTime:''});
      schedule[day]={...entry,versions};changed=true;
    }
    if(changed){await updateDoc(doc(db,'weeklyTemplates',t.id),{schedule,updatedAt:serverTimestamp()});retired++;}
  }
  // Cancel only future/pending snapshots; never delete or alter completed history.
  const future=await getDocs(query(collection(db,'dailyTasks'),where('date','>=',effectiveFrom)));
  for(const d of future.docs){const x=d.data();if(!x.hotFood&&LEGACY_HF_NAME.test(String(x.taskName||'').trim())&&activeStatus(x))await updateDoc(d.ref,{status:'cancelled',cancelReason:'Legacy Hot Food fixed check retired; replaced by controlled workflow',updatedAt:serverTimestamp()});}
  await setDoc(marker,{done:true,effectiveFrom,retired,updatedAt:serverTimestamp()});
  return {retired};
}
function previousDate(value){const d=new Date(value+'T12:00:00');d.setDate(d.getDate()-1);return `${d.getFullYear()}-${String(d.getMonth()+1).padStart(2,'0')}-${String(d.getDate()).padStart(2,'0')}`;}
export async function ensureHotFoodDay(date){
  const cfg=await getHotFoodConfig(); if(!cfg.enabled) return;
  try{await retireLegacyHotFoodTemplates(isoDate(new Date()));}
  catch(error){console.warn('Legacy Hot Food template retirement could not finish; daily workflow remains available',error);}
  await cancelLegacyTemperatureTasks(date);
  const dow=new Date(date+'T12:00:00').getDay();
  // Saturday/Sunday are manual-start days: no automatic Initial/Second Cooking tasks.
  if(dow===0||dow===6){
    const q=await getDocs(query(collection(db,'dailyTasks'),where('date','==',date)));
    for(const d of q.docs){
      const x=d.data();
      if(x.hotFood===true&&['cooking_initial','cooking_second'].includes(x.hotFoodType)&&activeStatus(x))
        await updateDoc(d.ref,{status:'cancelled',cancelReason:'Weekend Hot Food is manual start',updatedAt:serverTimestamp()});
    }
    await reconcileHotFoodDay(date);
    return;
  }
  const s=hotFoodSchedule(date),clock=cfg.initialCookingTime||s.initial;
  const day=dayKey(date),explicit=cfg.initialCookingStaffByDay?.[day]||'';
  const ownerDoc=doc(db,'system','hotFoodCookingAssignee_'+day);
  const prior=await getDoc(ownerDoc);
  const chosen=explicit?{id:explicit,name:(await getUsers()).find(u=>u.id===explicit)?.name||'Unassigned'}:
    prior.exists()?{id:prior.data().staffId||'',name:prior.data().staffName||'Unassigned'}:await chooseAssignee(date,clock);
  if(!prior.exists()&&chosen?.id)await runTransaction(db,async tx=>{const s=await tx.get(ownerDoc);if(!s.exists())tx.set(ownerDoc,{staffId:chosen.id,staffName:chosen.name||'Unassigned',firstScheduledOn:date,createdAt:serverTimestamp()});});
  await upsertHFTask(`hf_${date}_initial`,{date,taskName:'Initial Cooking',hotFoodType:'cooking_initial',sourceTime:clock,checkpoint:clock,slotId:slotForClock(clock,date),effortMinutes:Number(cfg.initialCookingEffortMinutes||15),assignedTo:chosen?.id||'',assignedName:chosen?.name||'Unassigned'});
  // V4.3: top-ups are staff-initiated with the always-available Start Cooking button.
  // Retire only the old incomplete automatic prompt. Never rewrite completed records.
  const oldTopUp=doc(db,'dailyTasks',`hf_${date}_second`);
  const oldSnap=await getDoc(oldTopUp);
  if(oldSnap.exists() && activeStatus(oldSnap.data()))
    await updateDoc(oldTopUp,{status:'cancelled',cancelReason:'Automatic 10:00 top-up retired; use Start Cooking',updatedAt:serverTimestamp()});
  await reconcileHotFoodDay(date);
}
